## 先定义维护成本

增加一个功能前，要考虑：

- 数据多久更新一次
- 谁来更新
- 失败后能不能发现
- 会不会增加依赖
- 公开页面是否需要

自动同步是降低维护成本的手段，不是增加入口的理由。

## 内容比框架重要

访问者不会因为网站用了多少技术就长期回来。清晰的文章、可验证的项目说明和稳定入口更重要。

