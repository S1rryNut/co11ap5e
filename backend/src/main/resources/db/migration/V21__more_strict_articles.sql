每一步都可能把正确内容丢掉。

## 切分不是固定 500 字

固定长度切分最容易实现，但不一定适合业务。需要判断：

- 标题是否保留
- 表格是否拆散
- 代码是否完整
- 上下文是否断裂
- 元数据是否保留

切分策略必须用真实文档测试。

## 检索相关性

向量相似度高不代表能回答问题。可能只是关键词相似，或者两个句子都提到同一件事，但缺少关键事实。

