```

单一检索模式容易漏召回或误召回。

## 重排

Top-N 召回后不能直接拼进 Prompt。用 Rerank 重新打分，过滤低相关内容。

重排能解决：

- 相似但无关
- 关键词匹配但语义不符
- 上下文太长

## 生成约束

Prompt 要明确：

- 只根据给定资料回答
- 资料不足就说明
- 输出引用
- 不编造来源

生成约束不能替代检索质量，但能减少幻觉。

## 结论

RAG 是一条完整流水线。每个环节都要单独检查和评测，向量入库只是中间步骤。
