## 虚拟列表解决的问题

几百条或几千条数据全部渲染时，DOM 节点会明显增加。虚拟列表只渲染可见区域：

```text
可见起点
  -> 可见终点
  -> 上下 overscan
```

这确实能降低初次渲染和滚动成本，但它不是全部。

## 固定高度只是最简单情况

如果每行高度固定，计算简单：

```ts
const start = Math.floor(scrollTop / itemHeight)
const end = Math.ceil((scrollTop + viewportHeight) / itemHeight)
```

实际问题常常包括：

- 摘要长度不同
- 移动端换行
- 图片高度变化
- 折叠区域展开
- 不同状态显示不同内容

固定高度模型在这里会错位。

## 高度测量

不固定高度需要测量。测量时要注意：

- 用 `ResizeObserver`
- 异步图片加载后重新测量
- 缓存已测量高度
- 增删节点后更新偏移
- 滚动位置不能跳

测量本身也会消耗性能，所以要避免每次都全量重新计算。

## 数据来源更关键

如果列表仍然一次性请求 5000 条数据，虚拟列表只是减少 DOM，网络和解析压力仍然存在。

更合理的是分页或游标：

```text
page / cursor
pageSize
total
```

虚拟列表适合已经拿到较大数据集、但浏览器渲染困难的场景，不适合替代接口分页。

## 搜索和筛选

客户端筛选时，过滤后需要重新计算偏移。服务端筛选则要处理请求抖动和分页状态。

两种方案都要处理：

- 筛选后回到合理位置
- 旧响应晚于新响应到达
- 空结果状态
- 加载更多失败

## 严格评价

虚拟列表有明确价值，但不应该被当作“性能优化完成”。没有高度模型、接口分页和状态同步，它只是把一个明显的问题换成另一个隐藏问题。
