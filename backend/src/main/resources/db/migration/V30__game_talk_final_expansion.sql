## 记录怎样更有价值

记录游戏时，我会把结论和依据分开。

```text
结论：推荐
依据：
- 单人也能玩
- 目标清晰
- 随时可暂停
- 存档完整
```

这样即使后来观点改变，也能知道当时为什么推荐。

游戏记录不是给谁看，而是给未来的自己一个准确判断。
