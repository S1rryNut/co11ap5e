## 常见误区

把 Agent 做得复杂，不代表它更可靠。工具越多，失败组合越多；步骤越多，状态越难恢复。

## 先明确任务

不是所有任务都需要 Agent。如果可以用一个确定流程完成，就不需要让模型反复选择动作。

适合 Agent 的条件：

- 任务分支较多
- 需要调用不同工具
- 中间结果影响下一步
- 用户只描述目标，不指定流程

## 工具少而准确

三个定义清楚的工具，通常比十个模糊工具更可靠。

每个工具必须：

- 知道何时使用
- 参数可验证
- 输出可解析
- 错误可恢复
- 权限可控制

## 失败路径

Agent 不是“一直重试直到成功”。必须定义：

- 最大步数
- 重复调用检测
- 工具错误分类
- 用户补充信息
- 终止原因

否则一次网络错误可能变成多次无效调用。

## 评测不能只看成功案例

困难问题同样重要：

- 工具失败
- 参数错误
- 无权限
- 结果冲突
- 用户中途取消

只展示最顺利的演示，会高估系统能力。

## 结论

Agent 的价值在于把复杂任务变成可追踪的步骤。复杂度本身不是能力，能够清楚结束、恢复和解释失败才是工程能力。
