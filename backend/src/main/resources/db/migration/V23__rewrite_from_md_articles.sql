## 存证到底需要什么

存证系统核心解决三件事：

- 数据不被篡改
- 操作能追溯
- 凭证可以核验

很多项目把防篡改和区块链绑在一起，但对中小型业务来说，这样容易过度设计。

## 哈希摘要

对核心数据生成 SHA-256 摘要，数据只要改一个字符，摘要就会完全不同。

```text
原始数据 -> SHA-256 -> 摘要
```

存证表里只保存摘要，不保存原始数据。这样能减少隐私风险，也能避免存证库变成业务数据副本。

## 时间戳

本地时间可以伪造，所以需要使用可信时间来源。

存证记录需要包含：

- 数据摘要
- 时间来源
- 业务标识

不要只存“当前时间字符串”，时间来源也要能说明。

## 链式关联

每一条新存证记录写入前一条的摘要：

```text
record 1: hash(data1)
record 2: hash(data1 + hash(data2))
record 3: hash(data2 + hash(data3))
```

这样单条记录被改，后面整条链都会校验失败。

## 轻量化方案的优点

- 不需要节点
- 不需要共识
- 不需要大量运维

缺点是它解决的是“数据可校验”，不是“分布式可信网络”。如果需要跨组织共识，再考虑区块链。

## 避坑

- 不要只存原始数据，不存摘要
- 数据更新不要覆盖旧记录，应该新增存证
- 校验逻辑和业务逻辑分开
- 时间戳来源要统一
