## 一个常见错误

很多前端系统会根据用户角色隐藏按钮：

```vue
<button v-if="user.role === 'ADMIN'">删除</button>
```

这只能改善界面，不能作为权限控制。任何人修改前端状态或直接调用接口，都可能绕过这个按钮。

## 前端权限的作用

前端权限的价值是：

- 减少用户误操作
- 减少没有意义的请求
- 让不同角色看到合适功能
- 提前告诉用户当前不可操作

它不能替代服务端校验。

## 服务端必须重复判断

即使前端已经隐藏删除按钮，后端仍然要：

1. 确认用户已经登录
2. 确认用户有删除权限
3. 确认资源 ID 属于可操作范围
4. 确认资源当前状态允许删除
5. 记录必要审计信息

只校验登录态不够。普通用户也可能猜出管理接口。

## 资源 ID 不能信任

```text
DELETE /api/admin/articles/123
```

接口不能因为 URL 在后台页面中就默认安全。服务端要把资源 ID 和当前管理员权限绑定。

## 二次确认不是权限

签名、删除、确认等操作的二次确认是体验层。攻击者可以绕过前端直接提交请求。

二次确认应该解决的是：

- 用户是不是误点击
- 风险是否足够清楚
- 用户有没有机会取消

它不能解决授权问题。

## 批量权限要检查每一条

批量删除、批量审核不能只判断“用户有权限操作这个接口”。要检查：

- 每条资源是否允许操作
- 是否存在越权资源 ID
- 是否存在重复 ID
- 失败后是否需要整体回滚

如果返回“部分成功”，页面必须明确列出来。

## 严格但合理的判断

前端安全边界应该让页面更清晰，但不能制造一种虚假的安全感。判断一个权限实现是否可靠，直接绕过页面调用接口最有效。
