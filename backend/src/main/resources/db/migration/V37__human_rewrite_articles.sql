更新逻辑更是让人无语。官方坚持"增量更新"，每个版本都新增战甲、武器、外观、新系统，就是不肯重构老化的底层玩法、引导系统和资源体系。老 bug 留着，不合理的掉落留着，繁琐的操作留着，冗余的流程也留着。系统越来越多，游戏越来越臃肿。对老玩家来说，新版本还有新东西可玩；对新玩家来说，光是搞懂这个游戏的系统，就已经劝退了一半人。游戏的新手引导常年被社区吐槽"等于没有"，不是官方不想做，而是这套复杂度已经超出了引导能覆盖的范围。

