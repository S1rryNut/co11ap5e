## 再谈竞技平衡和体验

Apex 的竞技体验很难用一个版本评价。

角色强度、武器池、地图改动、匹配规则都会改变体验。某个赛季难玩，不一定是玩法不行，也可能是版本调整和玩家群体变化共同造成。

作为玩家，我能接受平衡变化，但不接受：

- 版本改得太大，导致手感突然变化
- 匹配差距过大
- 失败反馈只来自数值，而不是操作

射击游戏最重要的是反馈一致性。枪械和后坐力稳定，玩家才愿意练习。
