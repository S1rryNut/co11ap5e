## JWT 与 Session 的取舍

JWT 的“无状态”有时被过度美化。真正无状态会带来吊销困难，所以生产项目往往仍然需要服务端保存 RefreshToken 或会话状态。

选择 Session 还是 JWT，取决于：

- 是否多端
- 是否分布部署
- 是否必须主动吊销
- 数据规模

没有绝对更优。JWT 适合跨端和扩展，Session 更适合简单和可控吊销。
