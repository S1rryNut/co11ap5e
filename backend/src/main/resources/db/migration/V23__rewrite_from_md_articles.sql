## JWT 为什么常见

传统 Session 存在服务端内存，分布式部署时要额外处理会话共享，跨域和移动端使用也不方便。

JWT 把身份信息放在客户端 token 里，服务端通过签名校验。适合多端、前后端分离、无状态扩展的场景。

## JWT 结构

```text
Header.Payload.Signature
```

- Header：算法和类型
- Payload：身份、权限、过期时间
- Signature：服务端密钥签名

Payload 可以解析，不能放密码、手机号等敏感数据。

## 落地流程

```text
登录
  -> 校验账号密码
  -> 生成 AccessToken
  -> 客户端存储
  -> 后续请求带 Authorization
  -> 服务端校验签名和过期
```

只在前端拦截路由不够，所有受保护接口都要在后端校验。

## 高频坑点

### 密钥硬编码

密钥写在代码里，token 可以被伪造。应该从环境变量或配置中心读取。

### 过期时间太长

JWT 默认不主动作废，token 只要没过期就能继续用。过期时间过长，账号泄露后风险也大。

### Payload 放敏感信息

JWT 的 Payload 可解析，不要放隐私字段。

### 接口裸奔

如果只有部分接口校验，其他管理接口可以被直接调用。

## 双 token

短时效 AccessToken + 长时效 RefreshToken 是常见方案。

```text
AccessToken 短，正常访问
RefreshToken 长，换取新 AccessToken
```

RefreshToken 需要服务端存储或吊销机制，不能只当 JWT 使用。

## 结论

JWT 解决的是无状态认证，不是安全问题。密钥管理、过期策略、接口覆盖和敏感数据才是真正决定安全的部分。
