### 落地时的几个坑

落地的时候有几个坑，我都踩过，给你排掉：

第一，只存哈希，不存原始数据。存证表里就放 `data_hash` 和 `prev_hash`，原始数据留在业务表，别图省事把整份数据塞进去。一来节省存储，二来避免敏感数据扩散——存证表本身不成为泄露源。

第二，更新走增量，不走覆盖。业务数据修改后生成一条新存证，旧记录保留。这样任何时候的历史都是可验证的，改掉重写是自毁证据。这里有个细节：修改后的新哈希跟旧哈希一起存，形成"版本链"，这样才能证明"这条数据从哪版改到了哪版"。

第三，校验逻辑和业务逻辑彻底解耦。校验单独做成一个服务，别混在业务代码里。链式校验就是从最后一条往前，逐条比对 `prev_hash` 是否等于上一条的 `data_hash`，对不上就抛异常。校验做成独立服务还有个好处：可以对外提供"验真接口"，让第三方也能验证你的存证是否可信——这在需要向监管或对方举证的时候很有用。

