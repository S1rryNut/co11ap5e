## 以前玩完就忘了

以前通关一个游戏，最多记住一个印象：好玩，或者没意思。

时间久了，连名字都可能记不清。

## 开始记录之后

我会记：

- 玩了多少小时
- 什么阶段开始好玩
- 哪里让我不想继续
- 会不会推荐给别人

这些记录不是为了显得专业，是为了以后能回想起当时为什么喜欢。

## 时长不是唯一标准

有的游戏玩了 1000 小时，但可能只是重复。

有的游戏只玩 20 小时，却一直记得。

所以游戏档案里，评分、锐评和随笔比单纯的时长更重要。

## 怎么记

我一般按这个顺序：

```text
游戏状态
  -> 评分
  -> 一句话锐评
  -> 完整随笔
  -> 是否推荐
```

先写结论，再补理由。

## 结尾

游戏本来也是生活记录的一部分。愿意玩下去的游戏，值得被好好记下来。
