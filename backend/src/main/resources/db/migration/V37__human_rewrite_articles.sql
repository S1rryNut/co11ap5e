### 先搞懂哈希到底能干什么

要理解为什么不用区块链也能防篡改，得先懂一个底层概念——哈希。SHA-256 这类哈希算法，能把任意长度的数据压缩成一个固定长度的"指纹"，而且有两个关键性质：第一，输入任何一点变化，输出就完全不同（雪崩效应）；第二，几乎不可能从哈希反推出原始数据（单向性）。这两条性质，就是"数据不可篡改"的数学基础——你改了数据，指纹就对不上，一验就知道。

更妙的是，哈希可以"链"起来：把上一条记录的哈希写进当前这条记录，形成一条链。任何一环的数据被改，它后面的每一环校验都会断掉——因为每条都依赖前一条的哈希。这就是"链式哈希"，也是区块链底层用的"默克尔链"思路的简化版。中小业务要的"防篡改 + 可追溯"，这套轻量方案完全够用。

