## 什么样的服务型可以接受

我并不是不接受服务型游戏，只是更看重边界：

- 更新是否改变核心玩法
- 不参与赛季会不会影响基本体验
- 付费是否只影响外观或便利
- 玩家能不能随时暂停

如果一款游戏让玩家觉得“不玩就亏”，那不是服务，是压力。

真正好的服务型，应该让玩家因为内容而回来，而不是因为焦虑而回来。
