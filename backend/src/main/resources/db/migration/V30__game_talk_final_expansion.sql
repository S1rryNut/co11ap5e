## 再谈回坑成本

Destiny 2 对老玩家和新玩家的回坑成本差别很大。

老玩家有装备基础，但新版本可能让旧装备失去价值。新玩家没有基础，又面临大量系统需要理解。

这暴露了服务型游戏的结构问题：

- 内容更新不能只考虑在线玩家
- 需要清晰的“当前赛季目标”
- 旧内容要么有说明，要么有独立入口

战斗本身依然值得肯定，但内容导航和用户分层确实需要改进。
