- 数十种独立货币、材料、道具
- MOD、裂罅、玄骸、振幅晶体、赋能各自独立
- 获取渠道和升级逻辑完全不同
- 新手被海量系统淹没

## 玩法固化

大多数任务围绕歼灭、生存、防御、拦截几类模板展开。

只是更换地图、怪物等级和掉落道具，核心机制常年不变。

后期游玩变成机械重复刷取。

## 更新逻辑

官方坚持“增量更新”，每版本新增战甲、武器、外观、新系统。

却从不重构老化的底层玩法、引导系统、资源体系。

旧 BUG、不合理掉落、繁琐操作、冗余流程常年保留。

## 叙事碎片化

优质主线篇章惊艳，但大量世界观和背景故事藏在资料库、任务碎片、文本日志里。

不主动翻阅海量文本，很难理解完整剧情。

## 社区断层

老玩家拥有海量资源和毕业配置，体验轻松自由。

新玩家面对杂乱系统、低掉落概率、繁琐刷取，入门过程枯燥煎熬。

“肝度是否合理”成为社区长期争议。

## 优化建议

针对系统冗余：

- 合并功能重复的货币、材料、道具
- 简化升级、合成、洗练流程
- 渐进式解锁玩法

针对肝度：

- 区分主线刚需和毕业追求
- 降低基础配装难度
- 保留高难度内容给核心玩家

针对更新和叙事：

- 每版本预留底层重构名额
- 定期修复历史 BUG
- 整合碎片化剧情

