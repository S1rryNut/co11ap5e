## 推荐还要看“状态”

同一款游戏，不同状态下体验完全不同。

时间多时，适合尝试内容深的游戏。时间少时，更适合短局和低压力游戏。

所以我推荐时会补充：

- 适合一个人还是多人
- 适合沉浸玩还是碎片玩
- 适合喜欢目标感还是喜欢自由探索

如果只列游戏名和评分，推荐并没有真正帮到别人。
