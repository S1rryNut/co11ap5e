## 一开始没有自己的电脑

我出生在 2004 年。小时候家里电脑不是我的，游戏机也不像现在这么普及。

最早接触游戏往往是在别人家里，或者蹭亲戚的掌机。那时候能玩到一局游戏，已经很开心。

## 网吧是另一个世界

再大一点，网吧成了同学之间共同的去处。一群人挤在一起打联机，看别人玩也能看很久。

那时的游戏没有那么多教程，很多东西是靠身边人教的。谁会用某个角色、谁懂某个地图，天然就是“高手”。

## 后来有了自己的 Steam 库

到了能自己买游戏的年纪，Steam 把我以前只能听别人聊的游戏变成了自己的库。

我会看评价、看时长、看打折。游戏不再是“别人电脑上有什么玩什么”，而是开始有自己的选择。

## 现在的习惯

现在玩得更多是：

- 能重玩的游戏
- 朋友一起玩的游戏
- 更新还算克制的游戏

对服务型游戏越来越谨慎，不是不愿意花钱，而是不想把游戏玩成每天打卡。

## 为什么愿意记录

年龄增长后，游戏时间变少，记忆反而更值钱。

写过的东西、玩过的版本、一起玩的人，都值得留下一点记录。
