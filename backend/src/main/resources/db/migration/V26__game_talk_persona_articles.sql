## 推荐标准

我自己的标准很简单：

- 能存档，不会几天不玩就落后
- 单人或少量朋友就能玩
- 玩法不会因为版本更新突然变质
- 随时打开都能找到目标

## 星露谷物语

种田、钓鱼、挖矿、经营社区。节奏慢，但目标很清晰。

适合时间零碎的人，因为每天很短，存档方便，不玩几天也不会焦虑。

## 泰拉瑞亚

探索、建造、打 Boss。看起来像 2D，但内容量很大。

更适合喜欢自己找目标和配装的玩家，不太适合只想一路被任务带的人。

## 杀戮尖塔

每局重新选卡，局内决策比长时间练操作更重要。

死亡不难受，因为下一局很快。适合想玩但不想投入大量时间的场景。

## 雨中冒险 2

多人合作，每局都会越来越乱，也很有趣。

和朋友一起玩时，互相补装备和技能，体验会比单排好很多。

## 双人成行

必须两个人玩，但流程设计和合作玩法很完整。

适合和熟悉的人一起通关，不是那种“一个人带着另一个人混”的联机。

## 怪物猎人：世界

刷素材、做装备、练不同武器。

前期需要耐心，但一旦理解怪物和武器节奏，会变得很耐玩。

## 最后说一句

推荐不是要求每个人都喜欢。能让我反复打开，就是它最大的价值。
